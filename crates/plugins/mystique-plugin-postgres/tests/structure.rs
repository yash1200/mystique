//! Live structure edits and schema diff against Postgres: create tables
//! with partial, expression, and INCLUDE indexes, defaults, identity,
//! CHECK, UNIQUE, and FK actions; apply edits; read back and compare.
//!
//! `cargo test -p mystique-plugin-postgres --test structure -- --ignored`

use mystique_connector_api::{
    plan_schema_diff_with, plan_table_alter, ConnectionConfig, ConnectorSession, ConstraintDraft,
    DatabaseConnector, DdlTarget, DiffSelection, DropKey, PoolConfig, QueryControl, QueryMode,
    TableDefinition, ValidatedQuery,
};
use mystique_plugin_postgres::PostgresConnector;
use serde_json::{json, Value as JsonValue};

async fn session() -> Box<dyn ConnectorSession> {
    let user = std::env::var("USER").unwrap_or_else(|_| "yashjohri".into());
    PostgresConnector
        .connect(&ConnectionConfig {
            engine: "postgres".into(),
            plugin_config: json!({
                "host": "127.0.0.1",
                "port": 5432,
                "database": "postgres",
                "username": user
            }),
            password: None,
            pool: PoolConfig {
                max_size: 2,
                min_idle: 0,
                acquire_timeout_ms: 5_000,
                idle_timeout_secs: 10,
            },
        })
        .await
        .expect("connect")
}

async fn run(session: &dyn ConnectorSession, text: &str) -> Vec<Vec<JsonValue>> {
    let query = ValidatedQuery {
        text: text.into(),
        mode: QueryMode::Write,
        max_rows: 100,
        timeout_ms: 10_000,
        collection: None,
        database: None,
        control: QueryControl::new(),
        params: Vec::new(),
    };
    session
        .execute_query(&query)
        .await
        .unwrap_or_else(|err| panic!("{text}: {err}"))
        .rows
}

async fn describe(session: &dyn ConnectorSession, schema: &str, table: &str) -> TableDefinition {
    session
        .describe_table_definition(None, Some(schema), table, Some("table"))
        .await
        .expect("describe")
}

async fn apply(session: &dyn ConnectorSession, draft: &TableDefinition) {
    let plan = plan_table_alter(DdlTarget::POSTGRES, draft);
    assert!(plan.applyable(), "{:?}", plan.warnings);
    session
        .apply_ddl(&plan, draft)
        .await
        .unwrap_or_else(|err| panic!("{err}\n{}", plan.statements.join(";\n")));
}

fn index_sql<'a>(table: &'a TableDefinition, name: &str) -> &'a str {
    table
        .indexes
        .iter()
        .find(|index| index.name == name)
        .and_then(|index| index.definition.as_deref())
        .unwrap_or_else(|| panic!("no index {name}: {:?}", table.indexes))
}

const SCHEMA: &str = "
CREATE TABLE {s}.parent (id int PRIMARY KEY);
INSERT INTO {s}.parent VALUES (1), (2);
CREATE TABLE {s}.orders (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL DEFAULT 'new',
    qty int CHECK (qty >= 0),
    parent_id int,
    note text,
    CONSTRAINT orders_code_key UNIQUE (code),
    CONSTRAINT orders_parent_fk FOREIGN KEY (parent_id) REFERENCES {s}.parent (id) ON DELETE CASCADE
);
CREATE INDEX orders_open ON {s}.orders (qty) WHERE qty > 0;
CREATE INDEX orders_lower_note ON {s}.orders (lower(note));
CREATE INDEX orders_parent_incl ON {s}.orders (parent_id) INCLUDE (note);
INSERT INTO {s}.orders (code, qty, parent_id, note) VALUES ('a', 1, 1, 'x'), ('b', 0, 2, 'y');
";

async fn fresh_schema(session: &dyn ConnectorSession, schema: &str) {
    run(session, &format!("DROP SCHEMA IF EXISTS {schema} CASCADE")).await;
    run(session, &format!("CREATE SCHEMA {schema}")).await;
    run(session, &SCHEMA.replace("{s}", schema)).await;
}

#[tokio::test]
#[ignore = "needs local Postgres"]
async fn describe_and_edit_keep_index_definitions_and_constraints() {
    let session = session().await;
    let session = session.as_ref();
    let schema = "mq_eb_struct_a";
    fresh_schema(session, schema).await;

    let draft = describe(session, schema, "orders").await;
    assert!(index_sql(&draft, "orders_open").contains("WHERE (qty > 0)"));
    assert!(index_sql(&draft, "orders_lower_note").contains("lower(note)"));
    assert!(index_sql(&draft, "orders_parent_incl").contains("INCLUDE (note)"));
    assert!(
        !draft
            .indexes
            .iter()
            .any(|index| index.name == "orders_code_key"),
        "a UNIQUE constraint is a constraint, not an index: {:?}",
        draft.indexes
    );
    let id = &draft.columns[0];
    assert_eq!(id.identity.as_deref(), Some("by default"));
    assert_eq!(
        draft.columns[1].default_value.as_deref(),
        Some("'new'::text")
    );
    assert!(draft
        .constraints
        .iter()
        .any(|c| c.kind == "check" && c.expression.as_deref() == Some("(qty >= 0)")));
    assert!(draft
        .constraints
        .iter()
        .any(|c| c.kind == "unique" && c.name == "orders_code_key" && c.columns == ["code"]));
    assert_eq!(draft.foreign_keys[0].on_delete.as_deref(), Some("CASCADE"));

    // Edit: default, identity, a CHECK swap, the FK action, a UNIQUE drop.
    let mut edit = draft.clone();
    edit.columns[1].default_value = Some("'fresh'::text".into());
    edit.columns[0].identity = Some("always".into());
    for constraint in &mut edit.constraints {
        if constraint.kind == "check" {
            constraint.drop = true;
        }
        if constraint.name == "orders_code_key" {
            constraint.drop = true;
        }
    }
    edit.constraints.push(ConstraintDraft {
        kind: "check".into(),
        name: "orders_qty_small".into(),
        expression: Some("qty < 100".into()),
        ..ConstraintDraft::default()
    });
    edit.foreign_keys[0].on_delete = Some("SET NULL".into());
    let plan = plan_table_alter(DdlTarget::POSTGRES, &edit);
    assert!(
        plan.statements
            .iter()
            .any(|sql| sql.contains("DROP CONSTRAINT \"orders_parent_fk\"")),
        "{plan:?}"
    );
    apply(session, &edit).await;

    let again = describe(session, schema, "orders").await;
    assert_eq!(
        again.columns[1].default_value.as_deref(),
        Some("'fresh'::text")
    );
    assert_eq!(again.columns[0].identity.as_deref(), Some("always"));
    let checks: Vec<_> = again
        .constraints
        .iter()
        .map(|c| (c.kind.as_str(), c.name.as_str()))
        .collect();
    assert_eq!(checks, [("check", "orders_qty_small")]);
    assert_eq!(again.foreign_keys[0].on_delete.as_deref(), Some("SET NULL"));
    // Untouched indexes are exactly as they were.
    for name in ["orders_open", "orders_lower_note", "orders_parent_incl"] {
        assert_eq!(index_sql(&again, name), index_sql(&draft, name));
    }
    assert_eq!(
        run(
            session,
            &format!("SELECT count(*)::int FROM {schema}.orders")
        )
        .await,
        [[json!(2)]]
    );

    run(session, &format!("DROP SCHEMA {schema} CASCADE")).await;
    session.close().await.ok();
}

#[tokio::test]
#[ignore = "needs local Postgres"]
async fn schema_diff_replays_indexes_pairs_renames_and_keeps_drops_off() {
    let session = session().await;
    let session = session.as_ref();
    let (src, dst) = ("mq_eb_struct_src", "mq_eb_struct_dst");
    fresh_schema(session, src).await;
    fresh_schema(session, dst).await;
    // The target drifted: a renamed column, an extra column, a plain index
    // where the source has a partial one, a different FK action.
    run(
        session,
        &format!(
            "ALTER TABLE {dst}.orders RENAME COLUMN note TO memo;
             ALTER TABLE {dst}.orders ADD COLUMN legacy int;
             DROP INDEX {dst}.orders_open;
             CREATE INDEX orders_open ON {dst}.orders (qty);
             DROP INDEX {dst}.orders_lower_note;
             DROP INDEX {dst}.orders_parent_incl;
             ALTER TABLE {dst}.orders DROP CONSTRAINT orders_parent_fk;
             ALTER TABLE {dst}.orders ADD CONSTRAINT orders_parent_fk FOREIGN KEY (parent_id) REFERENCES {dst}.parent (id);"
        ),
    )
    .await;
    let list = |schema: &'static str| async move {
        session
            .list_table_definitions(None, Some(schema))
            .await
            .expect("list")
    };
    let source = list(src).await;
    let target = list(dst).await;

    let migration = plan_schema_diff_with(
        DdlTarget::POSTGRES,
        &source,
        &target,
        &[],
        &DiffSelection::default(),
    );
    assert!(migration.warnings.is_empty(), "{:?}", migration.warnings);
    let orders = migration
        .changes
        .iter()
        .find(|change| change.name == "orders")
        .expect("orders change");
    assert_eq!(
        orders.column_renames.len(),
        1,
        "{:?}",
        orders.column_renames
    );
    assert!(orders.column_renames[0].guessed);
    assert_eq!(
        (
            orders.column_renames[0].from.as_str(),
            orders.column_renames[0].to.as_str()
        ),
        ("note", "memo")
    );
    assert!(orders
        .drops
        .iter()
        .any(|drop| drop.kind == "column" && drop.name == "legacy" && !drop.included));
    let sql = orders.plan.statements.join(";\n");
    assert!(sql.contains("RENAME COLUMN \"memo\" TO \"note\""), "{sql}");
    assert!(!sql.contains("DROP COLUMN"), "{sql}");
    assert!(
        sql.contains(&format!(
            "ON \"{dst}\".\"orders\" USING btree (qty) WHERE (qty > 0)"
        )),
        "{sql}"
    );
    assert!(sql.contains("INCLUDE (note)"), "{sql}");
    assert!(
        sql.contains("DROP CONSTRAINT \"orders_parent_fk\""),
        "{sql}"
    );
    assert!(sql.contains("ON DELETE CASCADE"), "{sql}");

    for change in migration
        .changes
        .iter()
        .filter(|c| c.selected && c.action != "unchanged")
    {
        session
            .apply_ddl(&change.plan, &change.draft)
            .await
            .unwrap_or_else(|err| panic!("{err}\n{}", change.plan.statements.join(";\n")));
    }
    let after = describe(session, dst, "orders").await;
    let wanted = describe(session, src, "orders").await;
    for name in ["orders_open", "orders_lower_note", "orders_parent_incl"] {
        assert_eq!(
            index_sql(&after, name).replace(dst, src),
            index_sql(&wanted, name),
            "{name}"
        );
    }
    assert_eq!(after.foreign_keys[0].on_delete.as_deref(), Some("CASCADE"));
    assert!(
        after.columns.iter().any(|c| c.name == "legacy"),
        "drop was not chosen"
    );
    assert_eq!(
        run(
            session,
            &format!("SELECT note FROM {dst}.orders ORDER BY id")
        )
        .await,
        [[json!("x")], [json!("y")]],
        "the rename kept the data"
    );

    // Choosing the drop removes the column.
    let target = list(dst).await;
    let selection = DiffSelection {
        skip: Vec::new(),
        drops: vec![DropKey {
            table: "orders".into(),
            kind: "column".into(),
            name: "legacy".into(),
        }],
    };
    let migration = plan_schema_diff_with(DdlTarget::POSTGRES, &source, &target, &[], &selection);
    let orders = migration
        .changes
        .iter()
        .find(|change| change.name == "orders")
        .expect("orders change");
    assert_eq!(
        orders.plan.statements,
        [format!(
            "ALTER TABLE \"{dst}\".\"orders\" DROP COLUMN \"legacy\""
        )]
    );
    session
        .apply_ddl(&orders.plan, &orders.draft)
        .await
        .expect("drop");
    let after = describe(session, dst, "orders").await;
    assert!(!after.columns.iter().any(|c| c.name == "legacy"));

    run(
        session,
        &format!("DROP SCHEMA {src} CASCADE; DROP SCHEMA {dst} CASCADE"),
    )
    .await;
    session.close().await.ok();
}

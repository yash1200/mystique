//! Catalog → DBML for agent / MCP schema context.
//! The FE has a parallel serializer for the designer; this one is live-engine.

use mystique_connector_api::{CatalogColumnRow, CatalogRelationship};

fn quote_ident(name: &str) -> String {
    let n = name.trim();
    if n.is_empty() {
        return "unnamed".into();
    }
    if n.chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && n.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
    {
        return n.to_string();
    }
    format!("\"{}\"", n.replace('"', "\\\""))
}

/// Schema-qualify unless the schema is empty or Postgres `public` (on search_path).
/// `main` is a real schema on some Postgres DBs and is **not** on search_path —
/// never strip it (unqualified `FROM boards` then fails).
pub(crate) fn table_ident(schema: &str, table: &str) -> String {
    let s = schema.trim();
    let t = quote_ident(table);
    if s.is_empty() || s.eq_ignore_ascii_case("public") {
        t
    } else {
        format!("{}.{}", quote_ident(s), t)
    }
}

/// Build DBML from plugin catalog columns + FK (or inferred) relationships.
pub fn catalog_to_dbml(
    engine: &str,
    connection_name: &str,
    database: Option<&str>,
    columns: &[CatalogColumnRow],
    rels: &[CatalogRelationship],
) -> String {
    let family = if engine.eq_ignore_ascii_case("mongodb") {
        "nosql"
    } else {
        "sql"
    };
    let mut out = String::new();
    out.push_str("// Use DBML to define your database structure\n");
    out.push_str("// Docs: https://dbml.dbdiagram.io/docs\n");
    out.push_str(&format!(
        "// Generated by Mystique DB · connection: {}\n",
        connection_name.trim()
    ));
    out.push_str(&format!("// Engine: {engine}\n"));
    if let Some(db) = database.map(str::trim).filter(|s| !s.is_empty()) {
        out.push_str(&format!("// Database: {db}\n"));
    }
    if family == "nosql" {
        out.push_str(
            "// Family: NoSQL — Table blocks are collections; fields are document fields.\n",
        );
    } else {
        out.push_str("// Family: SQL — write SELECT-only queries in this dialect.\n");
        out.push_str(
            "// Use the schema-qualified name from each Table header (e.g. main.boards).\n",
        );
        out.push_str(
            "// Only `public` may be referenced unqualified; `main` is not on search_path.\n",
        );
    }
    out.push('\n');

    #[derive(Clone)]
    struct Col {
        name: String,
        data_type: String,
        pk: bool,
        nullable: bool,
    }
    use std::collections::BTreeMap;
    let mut tables: BTreeMap<(String, String), Vec<Col>> = BTreeMap::new();
    for row in columns {
        let schema = row.schema.clone().unwrap_or_default();
        tables
            .entry((schema, row.table.clone()))
            .or_default()
            .push(Col {
                name: row.column.clone(),
                data_type: if row.data_type.trim().is_empty() {
                    "text".into()
                } else {
                    row.data_type.clone()
                },
                pk: row.pk,
                nullable: row.nullable,
            });
    }

    if tables.is_empty() {
        out.push_str("// No tables or collections found in this database.\n");
        return out;
    }

    const MAX_TABLES: usize = 200;
    let truncated = tables.len() > MAX_TABLES;
    for ((schema, table), cols) in tables.iter().take(MAX_TABLES) {
        let label = table_ident(schema, table);
        out.push_str(&format!("Table {label} {{\n"));
        if cols.is_empty() {
            out.push_str("  // (no columns yet)\n");
        } else {
            for c in cols {
                let mut settings = Vec::new();
                if c.pk {
                    settings.push("primary key");
                }
                if !c.nullable {
                    settings.push("not null");
                }
                let setting_str = if settings.is_empty() {
                    String::new()
                } else {
                    format!(" [{}]", settings.join(", "))
                };
                out.push_str(&format!(
                    "  {} {}{}\n",
                    quote_ident(&c.name),
                    c.data_type.trim(),
                    setting_str
                ));
            }
        }
        out.push_str("}\n\n");
    }

    if !rels.is_empty() {
        out.push_str("// Relationships\n");
        for rel in rels {
            let from = table_ident(rel.from_schema.as_deref().unwrap_or(""), &rel.from_table);
            let to = table_ident(rel.to_schema.as_deref().unwrap_or(""), &rel.to_table);
            out.push_str(&format!(
                "Ref: {}.{} > {}.{}\n",
                from,
                quote_ident(&rel.from_column),
                to,
                quote_ident(&rel.to_column)
            ));
        }
        out.push('\n');
    }

    if truncated {
        out.push_str(&format!(
            "// Truncated: showing {MAX_TABLES} of {} objects. Use list_objects / describe_object for the rest.\n",
            tables.len()
        ));
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(schema: &str, table: &str, column: &str, pk: bool) -> CatalogColumnRow {
        CatalogColumnRow {
            database: None,
            schema: Some(schema.into()),
            table: table.into(),
            column: column.into(),
            data_type: "int".into(),
            nullable: !pk,
            pk,
        }
    }

    #[test]
    fn emits_table_and_ref() {
        let cols = vec![
            col("public", "users", "id", true),
            col("public", "orders", "user_id", false),
        ];
        let rels = vec![CatalogRelationship {
            from_schema: Some("public".into()),
            from_table: "orders".into(),
            from_column: "user_id".into(),
            to_schema: Some("public".into()),
            to_table: "users".into(),
            to_column: "id".into(),
            name: None,
        }];
        let dbml = catalog_to_dbml("postgres", "dev", Some("app"), &cols, &rels);
        assert!(dbml.contains("Table users"));
        assert!(dbml.contains("id int [primary key"));
        assert!(dbml.contains("Ref: orders.user_id > users.id"));
        assert!(dbml.contains("Engine: postgres"));
    }

    #[test]
    fn qualifies_main_schema() {
        let cols = vec![col("main", "boards", "id", true)];
        let dbml = catalog_to_dbml("postgres", "dev", None, &cols, &[]);
        assert!(dbml.contains("Table main.boards"), "{dbml}");
        assert!(!dbml.contains("Table boards {"), "{dbml}");
    }
}

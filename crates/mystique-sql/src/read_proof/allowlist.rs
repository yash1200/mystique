/// Schemas whose functions are the engine's own. A call qualified with any
/// other schema is a user function.
pub(super) fn builtin_schemas(dialect: SqlDialect) -> &'static [&'static str] {
    match dialect {
        SqlDialect::Postgres => &["pg_catalog"],
        SqlDialect::Mysql | SqlDialect::Sqlite | SqlDialect::Generic => &[],
    }
}

/// Exact names, then prefixes, that `dialect` may call in a read.
pub(super) fn allowlist(
    dialect: SqlDialect,
) -> (&'static [&'static [&'static str]], &'static [&'static str]) {
    match dialect {
        SqlDialect::Postgres => (&[COMMON, POSTGRES], POSTGRES_PREFIXES),
        SqlDialect::Mysql => (&[COMMON, MYSQL], MYSQL_PREFIXES),
        SqlDialect::Sqlite => (&[COMMON, SQLITE], &[]),
        SqlDialect::Generic => (&[COMMON], &[]),
    }
}

/// Why `name` is a known side effect, if it is one.
pub(super) fn denied(name: &str) -> Option<DenyKind> {
    if let Some((_, kind)) = DENY.iter().find(|(entry, _)| *entry == name) {
        return Some(*kind);
    }
    DENY_PREFIXES
        .iter()
        .find(|(prefix, _)| name.starts_with(prefix))
        .map(|(_, kind)| *kind)
}

/// `name` is on `dialect`'s allowlist.
pub(super) fn allowed(dialect: SqlDialect, name: &str) -> bool {
    let (tables, prefixes) = allowlist(dialect);
    tables
        .iter()
        .any(|table| table.binary_search(&name).is_ok())
        || prefixes.iter().any(|prefix| name.starts_with(prefix))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn check_table(label: &str, table: &[&str]) {
        for pair in table.windows(2) {
            assert!(
                pair[0] < pair[1],
                "{label}: `{}` must sort before `{}` and appear once",
                pair[0],
                pair[1]
            );
        }
        for name in table {
            assert_eq!(*name, name.to_ascii_lowercase(), "{label}: {name}");
            assert!(denied(name).is_none(), "{label}: `{name}` is also denied");
        }
    }

    #[test]
    fn tables_are_sorted_lowercase_and_unique() {
        check_table("COMMON", COMMON);
        check_table("POSTGRES", POSTGRES);
        check_table("MYSQL", MYSQL);
        check_table("SQLITE", SQLITE);
        for pair in DENY.windows(2) {
            assert_ne!(pair[0].0, pair[1].0);
        }
    }

    #[test]
    fn no_allowed_prefix_admits_a_denied_name() {
        for (name, _) in DENY {
            for dialect in [
                SqlDialect::Postgres,
                SqlDialect::Mysql,
                SqlDialect::Sqlite,
                SqlDialect::Generic,
            ] {
                // Deny is checked first; this keeps the tables honest anyway.
                let (_, prefixes) = allowlist(dialect);
                assert!(
                    !prefixes.iter().any(|prefix| name.starts_with(prefix)),
                    "{dialect:?}: prefix admits denied `{name}`"
                );
            }
        }
    }
}

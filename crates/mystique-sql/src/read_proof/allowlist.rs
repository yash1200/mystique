//! Data tables for [`super::read_proof`]: which functions a read may call.
//!
//! A function is a read when it is on its dialect's allowlist and not on the
//! denylist. Everything else fails closed: user-defined functions, extension
//! functions we have not listed, and every new built-in until it is added.
//!
//! To allow a function, add its lowercase name to the right table below and
//! keep the table sorted. `tests::tables_are_sorted_lowercase_and_unique`
//! checks the shape; `tests/read_proof.rs` calls every entry.

use crate::SqlDialect;

/// Why a known function is not a read. Checked before the allowlist.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DenyKind {
    /// Changes data or sequence state (`nextval`, `lo_import`).
    Writes,
    /// Takes or releases a lock (`pg_advisory_lock`, `GET_LOCK`).
    Locks,
    /// Sleeps or waits, holding the connection (`pg_sleep`, `SLEEP`, `BENCHMARK`).
    Waits,
    /// Reads or writes files on the database server (`pg_read_file`, `LOAD_FILE`).
    ServerFiles,
    /// Runs SQL on another connection, outside the read-only transaction (`dblink`).
    OtherConnection,
    /// Runs a SQL string it is given (`query_to_xml`, `ts_stat`).
    RunsSql,
    /// Changes a setting (`set_config`).
    Settings,
    /// Acts on other sessions or the server (`pg_terminate_backend`, `pg_reload_conf`).
    Admin,
    /// Loads native code (`load_extension`).
    LoadsCode,
}

impl DenyKind {
    /// Reads after the backticked name: "`nextval` may write".
    pub fn phrase(self) -> &'static str {
        match self {
            Self::Writes => "may write",
            Self::Locks => "takes or releases a lock",
            Self::Waits => "waits and holds the connection",
            Self::ServerFiles => "touches files on the server",
            Self::OtherConnection => "runs SQL on another connection",
            Self::RunsSql => "runs a SQL string",
            Self::Settings => "changes a setting",
            Self::Admin => "acts on the server or other sessions",
            Self::LoadsCode => "loads native code",
        }
    }
}


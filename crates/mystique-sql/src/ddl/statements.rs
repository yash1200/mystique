//! Quoting and the statement builders every SQL dialect shares.

use super::changes::{
    constraint_definition_changed, fk_definition_changed, index_definition_changed,
    index_text_changed, names_equal,
};
use super::sqlite_text::{Text, Tok};
use super::types::{ColumnDraft, ConstraintDraft, ForeignKeyDraft, IndexDraft, TableDefinition};
use super::DdlTarget;
use crate::quote_ident;

pub(super) fn quote(dialect: DdlTarget, name: &str) -> String {
    quote_ident(dialect.sql(), name.trim())
}

pub(super) fn qualify(dialect: DdlTarget, draft: &TableDefinition) -> String {
    let mut parts: Vec<&str> = Vec::new();
    if dialect.is_mysql() {
        if let Some(database) = draft
            .database
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
        {
            parts.push(database);
        }
    }
    if !dialect.is_sqlite() {
        if let Some(schema) = draft
            .schema
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
        {
            if !schema.eq_ignore_ascii_case("main") {
                parts.push(schema);
            }
        }
    }
    parts.push(draft.name.trim());
    parts
        .into_iter()
        .filter(|part| !part.is_empty())
        .map(|part| quote(dialect, part))
        .collect::<Vec<_>>()
        .join(".")
}

pub(super) fn quote_list(dialect: DdlTarget, names: &[String]) -> String {
    names
        .iter()
        .map(|name| quote(dialect, name))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `GENERATED … AS IDENTITY` / `AUTO_INCREMENT`; SQLite's AUTOINCREMENT is
/// written with the primary key instead.
pub(super) fn identity_sql(dialect: DdlTarget, identity: Option<&str>) -> Option<String> {
    let identity = identity.map(str::trim).filter(|text| !text.is_empty())?;
    if dialect.is_mysql() {
        return Some("AUTO_INCREMENT".into());
    }
    if dialect.is_sqlite() {
        return None;
    }
    if identity.eq_ignore_ascii_case("always") {
        Some("GENERATED ALWAYS AS IDENTITY".into())
    } else {
        Some("GENERATED BY DEFAULT AS IDENTITY".into())
    }
}

/// `name type [NOT NULL] [DEFAULT …] [identity]` for CREATE and ADD COLUMN.
pub(super) fn column_definition(dialect: DdlTarget, column: &ColumnDraft) -> String {
    let mut out = quote(dialect, &column.name);
    let data_type = column.data_type.trim();
    if !data_type.is_empty() {
        out.push(' ');
        out.push_str(data_type);
    }
    if !column.nullable {
        out.push_str(" NOT NULL");
    }
    if let Some(default) = column
        .default_value
        .as_deref()
        .map(str::trim)
        .filter(|text| !text.is_empty())
    {
        out.push_str(" DEFAULT ");
        out.push_str(default);
    }
    if let Some(identity) = identity_sql(dialect, column.identity.as_deref()) {
        out.push(' ');
        out.push_str(&identity);
    }
    out
}

pub(super) fn is_sqlite_autoincrement(column: &ColumnDraft) -> bool {
    column
        .identity
        .as_deref()
        .is_some_and(|identity| !identity.trim().is_empty())
}

pub(super) fn create_table_sql(dialect: DdlTarget, draft: &TableDefinition) -> String {
    let mut pk: Vec<&ColumnDraft> = draft
        .columns
        .iter()
        .filter(|column| !column.drop && column.pk_position > 0)
        .collect();
    pk.sort_by_key(|column| column.pk_position);
    // SQLite: AUTOINCREMENT only exists as `INTEGER PRIMARY KEY AUTOINCREMENT`.
    let inline_pk = dialect.is_sqlite() && pk.len() == 1 && is_sqlite_autoincrement(pk[0]);
    let mut lines = Vec::new();
    for column in draft.columns.iter().filter(|column| !column.drop) {
        let mut line = column_definition(dialect, column);
        if inline_pk && column.pk_position > 0 {
            line.push_str(" PRIMARY KEY AUTOINCREMENT");
        }
        lines.push(line);
    }
    if !pk.is_empty() && !inline_pk {
        let cols = pk
            .iter()
            .map(|column| quote(dialect, &column.name))
            .collect::<Vec<_>>()
            .join(", ");
        lines.push(format!("PRIMARY KEY ({cols})"));
    }
    for constraint in draft.constraints.iter().filter(|c| !c.drop) {
        if let Some(sql) = constraint_body(dialect, constraint) {
            lines.push(sql);
        }
    }
    if dialect.is_sqlite() {
        // SQLite has no ALTER TABLE ADD CONSTRAINT: keys go in the CREATE.
        for fk in draft.foreign_keys.iter().filter(|fk| !fk.drop) {
            lines.push(foreign_key_body(dialect, fk));
        }
    }
    format!(
        "CREATE TABLE {} ({})",
        qualify(dialect, draft),
        lines.join(", ")
    )
}

/// `[CONSTRAINT name] CHECK (…)` / `UNIQUE (…)`.
pub(super) fn constraint_body(dialect: DdlTarget, constraint: &ConstraintDraft) -> Option<String> {
    let name = constraint.name.trim();
    let prefix = if name.is_empty() {
        String::new()
    } else {
        format!("CONSTRAINT {} ", quote(dialect, name))
    };
    if constraint.kind.eq_ignore_ascii_case("check") {
        let expression = constraint.expression.as_deref()?.trim();
        Some(format!("{prefix}CHECK ({expression})"))
    } else if constraint.kind.eq_ignore_ascii_case("unique") {
        Some(format!(
            "{prefix}UNIQUE ({})",
            quote_list(dialect, &constraint.columns)
        ))
    } else {
        None
    }
}

/// `[CONSTRAINT name] FOREIGN KEY (…) REFERENCES … [ON DELETE …] [ON UPDATE …]`.
pub(super) fn foreign_key_body(dialect: DdlTarget, fk: &ForeignKeyDraft) -> String {
    let name = fk.name.trim();
    let prefix = if name.is_empty() {
        String::new()
    } else {
        format!("CONSTRAINT {} ", quote(dialect, name))
    };
    let ref_table = if dialect.is_sqlite() {
        quote(dialect, &fk.ref_table)
    } else {
        dialect.sql().quote_path(
            [
                fk.ref_schema.as_deref().unwrap_or(""),
                fk.ref_table.as_str(),
            ]
            .into_iter()
            .filter(|part| !part.is_empty()),
        )
    };
    let mut out = format!(
        "{prefix}FOREIGN KEY ({}) REFERENCES {ref_table} ({})",
        quote_list(dialect, &fk.columns),
        quote_list(dialect, &fk.ref_columns)
    );
    if let Some(action) = fk.on_delete.as_deref() {
        out.push_str(" ON DELETE ");
        out.push_str(action);
    }
    if let Some(action) = fk.on_update.as_deref() {
        out.push_str(" ON UPDATE ");
        out.push_str(action);
    }
    out
}

pub(super) fn drop_index_sql(dialect: DdlTarget, draft: &TableDefinition, name: &str) -> String {
    let quoted = quote(dialect, name);
    if dialect.is_mysql() {
        format!(
            "ALTER TABLE {} DROP INDEX {quoted}",
            qualify(dialect, draft)
        )
    } else if dialect.is_postgres() {
        let index = match draft
            .schema
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
        {
            Some(schema) => format!("{}.{}", quote(dialect, schema), quoted),
            None => quoted,
        };
        format!("DROP INDEX {index}")
    } else {
        format!("DROP INDEX {quoted}")
    }
}

/// `CREATE INDEX` for a new or edited index. A new index that carries the
/// engine's own definition (schema diff) is replayed from it, pointed at
/// this table, so expressions, WHERE, and INCLUDE survive.
pub(super) fn create_index_sql(
    dialect: DdlTarget,
    draft: &TableDefinition,
    index: &IndexDraft,
) -> String {
    let table = qualify(dialect, draft);
    let columns_edited = index.original.as_ref().is_some_and(|original| {
        original.unique != index.unique || !names_equal(&original.columns, &index.columns)
    });
    let use_text = index.original.is_none() || (index_text_changed(index) && !columns_edited);
    if use_text && !index.concurrent {
        if let Some(sql) = index
            .definition
            .as_deref()
            .and_then(|definition| retarget_index(definition, &table).ok())
        {
            return sql;
        }
    }
    let unique = if index.unique { "UNIQUE " } else { "" };
    let concurrently = if index.concurrent && dialect.is_postgres() {
        "CONCURRENTLY "
    } else {
        ""
    };
    format!(
        "CREATE {unique}INDEX {concurrently}{} ON {table} ({})",
        quote(dialect, &index.name),
        quote_list(dialect, &index.columns)
    )
}

/// Point a `CREATE INDEX … ON table …` at another table name. Refuses text
/// that is not one CREATE INDEX statement.
pub(super) fn retarget_index(definition: &str, table: &str) -> Result<String, String> {
    let text = Text::new(definition)?;
    if text.tokens.iter().any(|token| token.kind == Tok::Semi) {
        return Err("An index definition must be one statement.".into());
    }
    let mut at = 0;
    if !text.is_kw(at, "CREATE") {
        return Err("An index definition must start with CREATE.".into());
    }
    at += 1;
    if text.is_kw(at, "UNIQUE") {
        at += 1;
    }
    if !text.is_kw(at, "INDEX") {
        return Err("An index definition must be CREATE INDEX.".into());
    }
    let on = (at..text.len())
        .find(|&i| text.is_kw(i, "ON"))
        .ok_or("An index definition has no ON.")?;
    let mut first = on + 1;
    if text.is_kw(first, "ONLY") {
        first += 1;
    }
    if text.ident(first).is_none() {
        return Err("An index definition has no table.".into());
    }
    let mut last = first;
    while text.kind(last + 1) == Some(Tok::Dot) && text.ident(last + 2).is_some() {
        last += 2;
    }
    let before = &definition[..text.tokens[first].start];
    let after = &definition[text.tokens[last].end..];
    Ok(format!("{before}{table}{after}"))
}

pub(super) fn index_statements(
    dialect: DdlTarget,
    draft: &TableDefinition,
    include_drops: bool,
) -> Vec<String> {
    let mut out = Vec::new();
    for index in &draft.indexes {
        if index.primary {
            continue;
        }
        if include_drops && index.drop && index.original.is_some() {
            out.push(drop_index_sql(dialect, draft, &index.name));
            continue;
        }
        let changed = index_definition_changed(index);
        if changed && include_drops {
            out.push(drop_index_sql(dialect, draft, &index.name));
        }
        if (index.original.is_none() || changed) && !index.drop {
            out.push(create_index_sql(dialect, draft, index));
        }
    }
    out
}

/// Statements that remove something, and statements that add it back.
pub(super) type DropsAndAdds = (Vec<String>, Vec<String>);

/// DROP / ADD for foreign keys. A key changed under the same name is
/// dropped and added again.
pub(super) fn foreign_key_statements(dialect: DdlTarget, draft: &TableDefinition) -> DropsAndAdds {
    let mut drops = Vec::new();
    let mut adds = Vec::new();
    let table = qualify(dialect, draft);
    let drop_sql = |name: &str| {
        if dialect.is_mysql() {
            format!(
                "ALTER TABLE {table} DROP FOREIGN KEY {}",
                quote(dialect, name)
            )
        } else {
            format!(
                "ALTER TABLE {table} DROP CONSTRAINT {}",
                quote(dialect, name)
            )
        }
    };
    for fk in &draft.foreign_keys {
        let Some(original) = &fk.original else {
            if !fk.drop {
                adds.push(format!(
                    "ALTER TABLE {table} ADD {}",
                    foreign_key_body(dialect, fk)
                ));
            }
            continue;
        };
        if fk.drop {
            drops.push(drop_sql(&original.name));
        } else if fk_definition_changed(fk) || !original.name.eq_ignore_ascii_case(&fk.name) {
            drops.push(drop_sql(&original.name));
            adds.push(format!(
                "ALTER TABLE {table} ADD {}",
                foreign_key_body(dialect, fk)
            ));
        }
    }
    (drops, adds)
}

/// DROP / ADD for CHECK and UNIQUE constraints (Postgres and MySQL).
pub(super) fn constraint_statements(dialect: DdlTarget, draft: &TableDefinition) -> DropsAndAdds {
    let mut drops = Vec::new();
    let mut adds = Vec::new();
    let table = qualify(dialect, draft);
    let drop_sql = |kind: &str, name: &str| {
        let name = quote(dialect, name);
        if dialect.is_mysql() && kind.eq_ignore_ascii_case("check") {
            format!("ALTER TABLE {table} DROP CHECK {name}")
        } else if dialect.is_mysql() {
            format!("ALTER TABLE {table} DROP INDEX {name}")
        } else {
            format!("ALTER TABLE {table} DROP CONSTRAINT {name}")
        }
    };
    for constraint in &draft.constraints {
        let add = || {
            constraint_body(dialect, constraint)
                .map(|body| format!("ALTER TABLE {table} ADD {body}"))
        };
        match &constraint.original {
            None => {
                if !constraint.drop {
                    adds.extend(add());
                }
            }
            Some(original) => {
                let renamed = !original.name.eq_ignore_ascii_case(&constraint.name);
                if constraint.drop {
                    drops.push(drop_sql(&original.kind, &original.name));
                } else if constraint_definition_changed(constraint) || renamed {
                    drops.push(drop_sql(&original.kind, &original.name));
                    adds.extend(add());
                }
            }
        }
    }
    (drops, adds)
}

pub(super) fn rename_sql(dialect: DdlTarget, draft: &TableDefinition) -> Option<String> {
    let next = draft
        .rename_to
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())?;
    if next == draft.name.trim() {
        return None;
    }
    Some(format!(
        "ALTER TABLE {} RENAME TO {}",
        qualify(dialect, draft),
        quote(dialect, next)
    ))
}
